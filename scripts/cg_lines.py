#!/usr/bin/env python3
"""Collect every Kirko Chainz announcer line from src/chaingame.js and write the
server whitelist functions/api/announce_lines.js (only these lines can be voiced)."""
import re, pathlib, json
R = pathlib.Path(__file__).resolve().parent.parent
src = (R / "src/chaingame.js").read_text()
chains = re.findall(r'\{name:"([^"]+)",type:"', src)
def body(fn):
    i = src.index("function " + fn + "(")
    j = src.index("\nfunction ", i + 10)
    return src[i:j]
lines = set()
for fn in ("cgCall", "cgCallMiss"):
    b = body(fn)
    for m in re.finditer(r'"([^"\\]{4,140})"(\+chain\+"!")?', b):
        t, tpl = m.group(1), m.group(2)
        if tpl:
            for c in chains: lines.add(t + c + "!")
        elif re.search(r"[A-Za-z]{3}", t) and t[-1] in "!?":
            lines.add(t)
for m in re.finditer(r'cgSay\("([^"\\]{4,140})"', src):
    lines.add(m.group(1))
out = sorted(lines)
(R / "functions/api/announce_lines.js").write_text("// generated by scripts/cg_lines.py from src/chaingame.js — the only lines /api/announce will voice\nexport const LINES = " + json.dumps(out, indent=0) + ";\n")
print(f"announcer lines: {len(out)}")
